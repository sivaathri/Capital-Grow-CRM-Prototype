export const DB = {
  get(key, fallback) {
    try {
      const item = localStorage.getItem('cg_' + key);
      if (!item) return fallback;
      const parsed = JSON.parse(item);
      // Auto-migrate / normalize legacy statuses if needed
      if (Array.isArray(parsed)) {
        return parsed.map((entry) => {
          if (entry.crmStatus === 'Under Process' || entry.status === 'Under Process') {
            return {
              ...entry,
              status: entry.status === 'Under Process' ? 'Lead' : entry.status,
              crmStatus: entry.crmStatus === 'Under Process' ? 'Lead' : entry.crmStatus
            };
          }
          return entry;
        });
      }
      return parsed;
    } catch {
      return fallback;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem('cg_' + key, JSON.stringify(value));
    } catch (e) {
      console.error('Storage error', e);
    }
  }
};

